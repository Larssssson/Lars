/** Minuten lesbar: "45 Minuten", "2 Std. 5 Min." */
function formatMinutes(minutes: number): string {
  const m = Math.round(minutes);
  if (m < 60) return `${m} Minuten`;
  return `${Math.floor(m / 60)} Std. ${m % 60} Min.`;
}

